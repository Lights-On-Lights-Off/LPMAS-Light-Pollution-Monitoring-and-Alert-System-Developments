-- ============================================================
-- 7. UPDATED_AT AUTOMATICALLY REFRESHES
-- ============================================================

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;


drop trigger if exists trg_sensor_minute_aggregates_updated_at
    on public.sensor_minute_aggregates;

create trigger trg_sensor_minute_aggregates_updated_at
before update on public.sensor_minute_aggregates
for each row
execute function public.set_updated_at();


drop trigger if exists trg_monitoring_incidents_updated_at
    on public.monitoring_incidents;

create trigger trg_monitoring_incidents_updated_at
before update on public.monitoring_incidents
for each row
execute function public.set_updated_at();


drop trigger if exists trg_system_settings_updated_at
    on public.system_settings;

create trigger trg_system_settings_updated_at
before update on public.system_settings
for each row
execute function public.set_updated_at();


