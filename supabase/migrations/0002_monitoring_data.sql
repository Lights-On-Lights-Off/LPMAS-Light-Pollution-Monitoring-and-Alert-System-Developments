-- ============================================================
-- 1. SENSOR MINUTE AGGREGATES
-- ============================================================
-- Receives completed minute-level summaries from Raspberry Pi.
--
-- One row represents:
--   sensor + minute
--
-- Raw 10-second readings are NOT stored here.
-- ============================================================

create table if not exists public.sensor_minute_aggregates (
    id bigint generated by default as identity primary key,

    sensor_id text not null,
    greenhouse_id text not null,

    bucket_start timestamptz not null,
    phase_type text not null,

    sample_count integer not null default 0,

    avg_lux numeric(12,3) not null,
    min_lux numeric(12,3) not null,
    max_lux numeric(12,3) not null,

    safe_count integer not null default 0,
    warning_count integer not null default 0,
    violation_count integer not null default 0,

    updated_at timestamptz not null default now(),

    -- The Python backend currently uses:
    -- on_conflict="sensor_id,bucket_start"
    constraint sensor_minute_aggregates_sensor_bucket_unique
        unique (sensor_id, bucket_start),

    -- Data validation
    constraint sensor_minute_aggregates_phase_check
        check (phase_type in ('illumination', 'dark')),

    constraint sensor_minute_aggregates_sample_count_check
        check (sample_count >= 0),

    constraint sensor_minute_aggregates_safe_count_check
        check (safe_count >= 0),

    constraint sensor_minute_aggregates_warning_count_check
        check (warning_count >= 0),

    constraint sensor_minute_aggregates_violation_count_check
        check (violation_count >= 0),

    constraint sensor_minute_aggregates_lux_check
        check (
            avg_lux >= 0
            and min_lux >= 0
            and max_lux >= 0
            and min_lux <= max_lux
        )
);


-- Indexes for dashboard/history queries

create index if not exists idx_sensor_minute_aggregates_sensor
    on public.sensor_minute_aggregates (sensor_id);

create index if not exists idx_sensor_minute_aggregates_greenhouse
    on public.sensor_minute_aggregates (greenhouse_id);

create index if not exists idx_sensor_minute_aggregates_bucket
    on public.sensor_minute_aggregates (bucket_start desc);

create index if not exists idx_sensor_minute_aggregates_greenhouse_bucket
    on public.sensor_minute_aggregates (greenhouse_id, bucket_start desc);

create index if not exists idx_sensor_minute_aggregates_sensor_bucket
    on public.sensor_minute_aggregates (sensor_id, bucket_start desc);


-- ============================================================
-- 2. MONITORING INCIDENTS
-- ============================================================
-- Stores confirmed lighting violations generated by app.py.
--
-- Incident lifecycle:
--
--     open
--       ↓
--     acknowledged
--       ↓
--     resolved
--
-- A safe reading resolves an active incident.
-- ============================================================

create table if not exists public.monitoring_incidents (
    id bigint generated by default as identity primary key,

    -- ID of the incident generated by Raspberry Pi SQLite
    pi_incident_id bigint not null,

    sensor_id text not null,
    greenhouse_id text not null,

    phase_type text not null,

    opened_at timestamptz not null,
    resolved_at timestamptz,

    status text not null default 'open',

    peak_lux numeric(12,3) not null,
    lowest_lux numeric(12,3) not null,

    reason text not null,

    updated_at timestamptz not null default now(),

    -- Used by app.py:
    -- on_conflict="pi_incident_id"
    constraint monitoring_incidents_pi_id_unique
        unique (pi_incident_id),

    -- Valid incident statuses
    constraint monitoring_incidents_status_check
        check (status in ('open', 'acknowledged', 'resolved')),

    -- Valid phases
    constraint monitoring_incidents_phase_check
        check (phase_type in ('illumination', 'dark')),

    -- Lux values cannot be negative
    constraint monitoring_incidents_lux_check
        check (
            peak_lux >= 0
            and lowest_lux >= 0
        ),

    -- Peak must not be lower than lowest
    constraint monitoring_incidents_peak_low_check
        check (peak_lux >= lowest_lux),

    -- Resolved incidents must have a resolution time.
    -- Active incidents should not have one.
    constraint monitoring_incidents_resolution_check
        check (
            (status = 'resolved' and resolved_at is not null)
            or
            (status in ('open', 'acknowledged') and resolved_at is null)
        )
);


-- Indexes

create index if not exists idx_monitoring_incidents_sensor
    on public.monitoring_incidents (sensor_id);

create index if not exists idx_monitoring_incidents_greenhouse
    on public.monitoring_incidents (greenhouse_id);

create index if not exists idx_monitoring_incidents_status
    on public.monitoring_incidents (status);

create index if not exists idx_monitoring_incidents_opened
    on public.monitoring_incidents (opened_at desc);

create index if not exists idx_monitoring_incidents_greenhouse_status
    on public.monitoring_incidents (greenhouse_id, status);

create index if not exists idx_monitoring_incidents_sensor_status
    on public.monitoring_incidents (sensor_id, status);


-- ============================================================
-- 3. SYSTEM SETTINGS
-- ============================================================
-- Stores administrator/system configuration.
--
-- app.py specifically looks for:
--
--     key = 'manager_phone'
--
-- The Raspberry Pi uses the Supabase secret/service key to
-- retrieve this value.
--
-- IMPORTANT:
-- This table should NOT be publicly readable because it can
-- contain sensitive administrative configuration.
-- ============================================================

create table if not exists public.system_settings (
    id bigint generated by default as identity primary key,

    key text not null,
    value text,

    updated_at timestamptz not null default now(),

    constraint system_settings_key_unique
        unique (key),

    constraint system_settings_key_not_empty
        check (length(trim(key)) > 0)
);


-- Index for key lookups

create index if not exists idx_system_settings_key
    on public.system_settings (key);


