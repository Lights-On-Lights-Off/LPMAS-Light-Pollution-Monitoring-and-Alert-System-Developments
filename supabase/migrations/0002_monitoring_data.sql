-- ============================================================
-- 6. RLS POLICIES
-- ============================================================
--
-- SECURITY MODEL
--
-- Raspberry Pi app.py:
--     Uses SUPABASE_SECRET_KEY
--     → service-role/backend access
--     → bypasses normal RLS policies
--
-- Next.js/dashboard:
--     Uses normal Supabase client/auth
--     → authenticated users may READ dashboard/history data
--
-- Anonymous users:
--     Cannot read these tables.
--
-- system_settings:
--     Not readable by frontend users.
--     Only backend/service-role code should access it.
-- ============================================================


-- ------------------------------------------------------------
-- SENSOR MINUTE AGGREGATES
-- ------------------------------------------------------------

drop policy if exists "Authenticated users can view sensor aggregates"
    on public.sensor_minute_aggregates;

create policy "Authenticated users can view sensor aggregates"
on public.sensor_minute_aggregates
for select
to authenticated
using (true);


-- Explicitly prevent normal frontend users from inserting,
-- updating, or deleting cloud aggregates.
--
-- app.py uses the service-role/secret key, so its writes
-- continue to work without a frontend write policy.


drop policy if exists "Authenticated users cannot insert sensor aggregates"
    on public.sensor_minute_aggregates;

create policy "Authenticated users cannot insert sensor aggregates"
on public.sensor_minute_aggregates
for insert
to authenticated
with check (false);


drop policy if exists "Authenticated users cannot update sensor aggregates"
    on public.sensor_minute_aggregates;

create policy "Authenticated users cannot update sensor aggregates"
on public.sensor_minute_aggregates
for update
to authenticated
using (false)
with check (false);


drop policy if exists "Authenticated users cannot delete sensor aggregates"
    on public.sensor_minute_aggregates;

create policy "Authenticated users cannot delete sensor aggregates"
on public.sensor_minute_aggregates
for delete
to authenticated
using (false);


